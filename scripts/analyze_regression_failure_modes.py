#!/usr/bin/env python3
"""
Classify correct->wrong regressions into mutually exclusive failure modes and
render review-friendly case studies.

Inputs:
  - correct_to_wrong.csv generated by scripts/compare_badcase_runs.py

Outputs under --output-dir:
  - regression_3way_summary.json
  - regression_3way_report.md
  - regression_category_<slug>.csv
"""

from __future__ import annotations

import argparse
import csv
import json
import re
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any


CATEGORY_META = {
    "weak_graph_hit": {
        "label": "图命中弱",
        "description": "Graph retrieval is off-target, fallback-heavy, or misses the temporal anchor, so later reasoning starts from weak evidence.",
    },
    "coarse_graph_replaced_fine_inspect": {
        "label": "图太粗替代了细粒度 inspect",
        "description": "The question needs fine-grained visual confirmation, but segment/frame graph evidence is too coarse and the run under-confirms the key detail.",
    },
    "long_chain_wrong_convergence": {
        "label": "推理链变长但最后选项收敛错了",
        "description": "The run keeps searching after initial evidence, accumulates more steps, and converges to the wrong option anyway.",
    },
}

TOOL_SHORT = {
    "global_browse_tool": "GB",
    "clip_search_tool": "CS",
    "frame_inspect_tool": "FI",
    "frame_graph_query_tool": "FG",
    "segment_graph_query_tool": "SG",
    "finish": "FIN",
}

FINE_DETAIL_PATTERNS = [
    r"\bhow many\b",
    r"\bnumber of\b",
    r"\bwhat color\b",
    r"\bcolour\b",
    r"\bwear\b",
    r"\bwearing\b",
    r"\bclothes\b",
    r"\bhat\b",
    r"\bshirt\b",
    r"\bdress\b",
    r"\bglasses\b",
    r"\blook like\b",
    r"\bholding in (his|her|their) hand\b",
    r"^\s*who\b",
]


@dataclass
class ToolStep:
    step_idx: int
    tool_name: str
    tool_short: str
    query: str
    time_ranges: list[str]
    preview: str
    graph_top: str


@dataclass
class TraceDigest:
    tool_path: str
    finish_answer: str
    steps: list[ToolStep]


def _load_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def _write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fieldnames = list(rows[0].keys())
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def _write_json(path: Path, data: Any) -> None:
    with path.open("w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)


def _to_int(row: dict[str, str], key: str) -> int:
    try:
        return int(str(row.get(key, "")).strip() or 0)
    except Exception:
        return 0


def _to_bool(row: dict[str, str], key: str) -> bool:
    return str(row.get(key, "")).strip().lower() == "true"


def _tags(row: dict[str, str]) -> set[str]:
    value = str(row.get("tags", "")).strip()
    return {part for part in value.split("|") if part}


def _question_needs_fine_detail(row: dict[str, str], tags: set[str]) -> bool:
    if "fine_visual_detail_question" in tags:
        return True
    q = str(row.get("question", "")).strip().lower()
    return any(re.search(pattern, q) for pattern in FINE_DETAIL_PATTERNS)


def _question_has_temporal_cue(row: dict[str, str], tags: set[str]) -> bool:
    if "temporal_reasoning" in tags:
        return True
    return bool(str(row.get("time_reference", "")).strip())


def _primary_failure_mode(row: dict[str, str]) -> tuple[str, list[str]]:
    tags = _tags(row)
    reasons: list[str] = []

    baseline_llm = _to_int(row, "baseline_llm_calls")
    new_llm = _to_int(row, "new_llm_calls")
    baseline_steps = _to_int(row, "baseline_step_count")
    new_steps = _to_int(row, "new_step_count")
    baseline_fi = _to_int(row, "baseline_fi")
    new_fi = _to_int(row, "new_fi")
    baseline_fg = _to_int(row, "baseline_fg")
    new_fg = _to_int(row, "new_fg")
    new_sg = _to_int(row, "new_sg")
    new_graph_calls = new_fg + new_sg
    fine_detail = _question_needs_fine_detail(row, tags)
    has_temporal_cue = _question_has_temporal_cue(row, tags)
    weak_hit = (
        "weak_graph_fallback" in tags
        or "segment_graph_no_temporal_hit" in tags
        or _to_bool(row, "new_graph_fallback_used")
        or (_to_int(row, "new_graph_best_match_count") == 0 and new_graph_calls > 0)
        or (has_temporal_cue and new_sg > 0 and not _to_bool(row, "new_graph_best_temporal_hit"))
    )
    coarse_substitution = (
        fine_detail
        and (
            "segment_graph_may_be_too_coarse" in tags
            or "less_visual_confirmation" in tags
            or "graph_without_visual_confirmation" in tags
            or (new_sg > 0 and new_fg < baseline_fg)
            or (new_sg > 0 and new_fi <= baseline_fi)
        )
    )
    long_chain = (
        "longer_reasoning_but_wrong" in tags
        or new_llm >= baseline_llm + 3
        or new_steps >= baseline_steps + 3
    )

    if coarse_substitution:
        if fine_detail:
            reasons.append("question_needs_fine_detail")
        if new_sg > 0:
            reasons.append("segment_graph_used_on_fine_detail_question")
        if "segment_graph_may_be_too_coarse" in tags:
            reasons.append("segment_graph_tagged_too_coarse")
        if "less_visual_confirmation" in tags or new_fi < baseline_fi:
            reasons.append("less_visual_confirmation_than_baseline")
        if new_fg < baseline_fg:
            reasons.append("less_frame_graph_detail_than_baseline")
        return "coarse_graph_replaced_fine_inspect", reasons

    if long_chain:
        if new_llm > baseline_llm:
            reasons.append(f"llm_calls_{baseline_llm}_to_{new_llm}")
        if new_steps > baseline_steps:
            reasons.append(f"steps_{baseline_steps}_to_{new_steps}")
        if "longer_reasoning_but_wrong" in tags:
            reasons.append("tagged_longer_reasoning")
        if weak_hit:
            reasons.append("search_chain_built_on_weak_graph")
        return "long_chain_wrong_convergence", reasons

    if weak_hit or new_graph_calls > 0:
        if _to_bool(row, "new_graph_fallback_used"):
            reasons.append("graph_fallback_used")
        if "segment_graph_no_temporal_hit" in tags:
            reasons.append("segment_graph_missed_temporal_anchor")
        if _to_int(row, "new_graph_best_match_count") == 0 and new_graph_calls > 0:
            reasons.append("graph_returned_no_strong_match")
        if new_graph_calls > 0:
            reasons.append("graph_calls_present")
        return "weak_graph_hit", reasons

    reasons.append("default_bucket")
    return "weak_graph_hit", reasons


def _safe_json_load(raw: str) -> Any:
    try:
        return json.loads(raw)
    except Exception:
        return None


def _truncate(text: str, limit: int = 180) -> str:
    text = re.sub(r"\s+", " ", (text or "").strip())
    if len(text) <= limit:
        return text
    return text[: limit - 3].rstrip() + "..."


def _extract_query(tool_name: str, args: dict[str, Any]) -> str:
    if tool_name in {"frame_graph_query_tool", "segment_graph_query_tool", "global_browse_tool"}:
        return str(args.get("query", "")).strip()
    if tool_name == "clip_search_tool":
        return str(args.get("event_description", "")).strip()
    if tool_name == "frame_inspect_tool":
        return str(args.get("question", "")).strip()
    if tool_name == "finish":
        return str(args.get("answer", "")).strip()
    return ""


def _extract_time_ranges(args: dict[str, Any]) -> list[str]:
    ranges = args.get("time_ranges_hhmmss") or []
    out: list[str] = []
    if not isinstance(ranges, list):
        return out
    for item in ranges:
        if isinstance(item, list) and len(item) == 2:
            out.append(f"{item[0]}-{item[1]}")
    return out


def _extract_graph_top(preview: str) -> str:
    parsed = _safe_json_load(preview.strip())
    if not isinstance(parsed, dict):
        return ""

    matched = parsed.get("matched_segments") or parsed.get("matched_frames") or []
    if not isinstance(matched, list) or not matched:
        return ""

    top = matched[0]
    if not isinstance(top, dict):
        return ""

    if "segment_id" in top:
        start = top.get("t_start")
        end = top.get("t_end")
        summary = _truncate(str(top.get("summary", "")), 110)
        dist = top.get("temporal_distance_sec")
        return f"{top.get('segment_id')} {start}-{end}s dist={dist} {summary}".strip()

    if "frame_id" in top:
        ts = top.get("timestamp_sec")
        caption = _truncate(str(top.get("caption_context", "")), 110)
        dist = top.get("temporal_distance_sec")
        return f"{top.get('frame_id')} @{ts}s dist={dist} {caption}".strip()

    return ""


def _read_trace_digest(path: Path) -> TraceDigest:
    steps: list[ToolStep] = []
    tool_path_parts: list[str] = []
    finish_answer = ""

    with path.open("r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                event = json.loads(line)
            except json.JSONDecodeError:
                continue
            if event.get("event_type") != "tool_call":
                continue

            tool_name = str(event.get("tool_name", ""))
            tool_path_parts.append(TOOL_SHORT.get(tool_name, tool_name))
            raw_args = str(event.get("tool_args", "")).strip()
            args = _safe_json_load(raw_args) or {}
            preview = str(((event.get("tool_output_summary") or {}).get("preview")) or "")
            step = ToolStep(
                step_idx=int(event.get("step_idx") or 0),
                tool_name=tool_name,
                tool_short=TOOL_SHORT.get(tool_name, tool_name),
                query=_extract_query(tool_name, args),
                time_ranges=_extract_time_ranges(args),
                preview=_truncate(preview),
                graph_top=_extract_graph_top(preview),
            )
            if tool_name == "finish":
                finish_answer = step.query
            steps.append(step)

    return TraceDigest(tool_path=" > ".join(tool_path_parts), finish_answer=finish_answer, steps=steps)


def _step_line(step: ToolStep) -> str:
    parts = [step.tool_short]
    if step.query:
        parts.append(f"query=`{_truncate(step.query, 100)}`")
    if step.time_ranges:
        parts.append(f"time={', '.join(step.time_ranges)}")
    if step.graph_top:
        parts.append(f"top={step.graph_top}")
    elif step.preview and step.tool_short != "FIN":
        parts.append(f"obs={step.preview}")
    if step.tool_short == "FIN" and step.query:
        parts.append(f"answer={step.query}")
    return " | ".join(parts)


def _category_score(category: str, row: dict[str, str]) -> int:
    tags = _tags(row)
    baseline_llm = _to_int(row, "baseline_llm_calls")
    new_llm = _to_int(row, "new_llm_calls")
    baseline_steps = _to_int(row, "baseline_step_count")
    new_steps = _to_int(row, "new_step_count")
    baseline_fi = _to_int(row, "baseline_fi")
    new_fi = _to_int(row, "new_fi")
    baseline_fg = _to_int(row, "baseline_fg")
    new_fg = _to_int(row, "new_fg")
    new_sg = _to_int(row, "new_sg")

    if category == "weak_graph_hit":
        return (
            5 * int(_to_bool(row, "new_graph_fallback_used"))
            + 4 * int("segment_graph_no_temporal_hit" in tags)
            + 3 * int(_to_int(row, "new_graph_best_match_count") == 0)
            + 2 * int(new_sg > 0)
            + int(new_fg > 0)
        )

    if category == "coarse_graph_replaced_fine_inspect":
        return (
            4 * int("segment_graph_may_be_too_coarse" in tags)
            + 3 * int("less_visual_confirmation" in tags or new_fi < baseline_fi)
            + 2 * int(new_sg > 0)
            + 2 * int(new_fg < baseline_fg)
            + int(_question_needs_fine_detail(row, tags))
        )

    if category == "long_chain_wrong_convergence":
        return (
            3 * (new_llm - baseline_llm)
            + 2 * (new_steps - baseline_steps)
            + 2 * int("longer_reasoning_but_wrong" in tags)
            + int(new_fi > baseline_fi)
        )

    return 0


def _select_representatives(rows: list[dict[str, str]], category: str, limit: int = 5) -> list[dict[str, str]]:
    scored = sorted(
        rows,
        key=lambda row: (
            _category_score(category, row),
            _to_int(row, "new_llm_calls") - _to_int(row, "baseline_llm_calls"),
            _to_int(row, "new_step_count") - _to_int(row, "baseline_step_count"),
        ),
        reverse=True,
    )

    selected: list[dict[str, str]] = []
    used_videos: set[str] = set()
    for row in scored:
        video_id = row.get("video_id", "")
        if video_id in used_videos:
            continue
        selected.append(row)
        used_videos.add(video_id)
        if len(selected) == limit:
            return selected
    for row in scored:
        if row in selected:
            continue
        selected.append(row)
        if len(selected) == limit:
            break
    return selected


def _parse_time_anchor(row: dict[str, str]) -> str:
    value = str(row.get("time_reference", "")).strip()
    return value or "N/A"


def _failure_summary(category: str, row: dict[str, str], baseline: TraceDigest, new: TraceDigest) -> tuple[str, str]:
    tags = _tags(row)
    baseline_tool_path = row.get("baseline_tool_path", "")
    new_tool_path = row.get("new_tool_path", "")
    graph_evidence = row.get("new_graph_evidence", "")

    if category == "weak_graph_hit":
        why_right = (
            f"Baseline stayed on a shorter path `{baseline_tool_path}` and anchored the answer with direct search/inspect evidence."
        )
        why_wrong = (
            f"New run switched to `{new_tool_path}`, but the graph evidence was weak or off-target (`{graph_evidence or 'no strong graph hit'}`). "
            "That left the final answer resting on weak retrieval rather than question-specific confirmation."
        )
        if _to_bool(row, "new_graph_fallback_used"):
            why_wrong += " It also hit graph fallback."
        return why_right, why_wrong

    if category == "coarse_graph_replaced_fine_inspect":
        why_right = (
            f"Baseline used `{baseline_tool_path}` to verify the discriminative visual detail directly, which is the right shape for this question."
        )
        why_wrong = (
            f"New run leaned on `{new_tool_path}`. The graph summary is too coarse for this fine-detail question, "
            "and the confirmation step was weaker than baseline or came after a coarse graph anchor."
        )
        return why_right, why_wrong

    why_right = (
        f"Baseline solved it with a shorter chain `{baseline_tool_path}` and stopped once it had enough evidence."
    )
    why_wrong = (
        f"New run expanded to `{new_tool_path}`. The extra search steps did not add better evidence, "
        "and the agent still converged to the wrong option after a longer chain."
    )
    if "longer_reasoning_but_wrong" in tags:
        why_wrong += " This row is explicitly tagged `longer_reasoning_but_wrong`."
    return why_right, why_wrong


def _render_report(output_path: Path, rows: list[dict[str, str]]) -> dict[str, Any]:
    categorized: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        category, reasons = _primary_failure_mode(row)
        row["primary_failure_mode"] = category
        row["primary_failure_reasons"] = "|".join(reasons)
        categorized[category].append(row)

    total = len(rows)
    summary: dict[str, Any] = {
        "total_regressions": total,
        "categories": {},
    }
    lines: list[str] = []
    lines.append("# Correct->Wrong Regression Failure Modes")
    lines.append("")
    lines.append(
        f"This report partitions the {total} `correct -> wrong` regressions into one primary failure mode per trace."
    )
    lines.append("")
    lines.append("## Category Breakdown")
    lines.append("")
    lines.append("| Category | Count | Share | Mean llm delta | Mean step delta | Mean FI delta | SG involved | Graph fallback |")
    lines.append("|---|---:|---:|---:|---:|---:|---:|---:|")

    for category in CATEGORY_META:
        bucket = categorized.get(category, [])
        count = len(bucket)
        share = (count / total) if total else 0.0
        mean_llm_delta = sum(_to_int(r, "new_llm_calls") - _to_int(r, "baseline_llm_calls") for r in bucket) / count if count else 0.0
        mean_step_delta = sum(_to_int(r, "new_step_count") - _to_int(r, "baseline_step_count") for r in bucket) / count if count else 0.0
        mean_fi_delta = sum(_to_int(r, "new_fi") - _to_int(r, "baseline_fi") for r in bucket) / count if count else 0.0
        sg_involved = sum(1 for r in bucket if _to_int(r, "new_sg") > 0)
        fallback = sum(1 for r in bucket if _to_bool(r, "new_graph_fallback_used"))

        summary["categories"][category] = {
            "label": CATEGORY_META[category]["label"],
            "description": CATEGORY_META[category]["description"],
            "count": count,
            "share": share,
            "mean_llm_delta": mean_llm_delta,
            "mean_step_delta": mean_step_delta,
            "mean_fi_delta": mean_fi_delta,
            "sg_involved_count": sg_involved,
            "graph_fallback_count": fallback,
        }
        lines.append(
            f"| {CATEGORY_META[category]['label']} | {count} | {share:.1%} | {mean_llm_delta:+.2f} | {mean_step_delta:+.2f} | {mean_fi_delta:+.2f} | {sg_involved}/{count} | {fallback}/{count} |"
        )

    for category in CATEGORY_META:
        bucket = categorized.get(category, [])
        bucket.sort(key=lambda row: (row.get("video_id", ""), int(row.get("qid", "0"))))
        reps = _select_representatives(bucket, category, limit=5)
        summary["categories"][category]["representatives"] = [row["trace_id"] for row in reps]

        lines.append("")
        lines.append(f"## {CATEGORY_META[category]['label']}")
        lines.append("")
        lines.append(CATEGORY_META[category]["description"])
        lines.append("")
        tag_counter = Counter()
        for row in bucket:
            tag_counter.update(_tags(row))
        lines.append("Top tags:")
        lines.append("")
        for tag, count in tag_counter.most_common(8):
            lines.append(f"- `{tag}`: {count}")
        lines.append("")
        lines.append("Representative cases:")
        lines.append("")

        for row in reps:
            baseline = _read_trace_digest(Path(row["baseline_trace_path"]))
            new = _read_trace_digest(Path(row["new_trace_path"]))
            why_right, why_wrong = _failure_summary(category, row, baseline, new)
            lines.append(f"### qid {row['qid']} | video `{row['video_id']}`")
            lines.append("")
            lines.append(f"- Question: `{row['question']}`")
            lines.append(f"- Time reference: `{_parse_time_anchor(row)}`")
            lines.append(f"- Expected / baseline / new: `{row['expected']}` / `{row['baseline_pred']}` / `{row['new_pred']}`")
            lines.append(f"- Baseline path: `{row['baseline_tool_path']}`")
            lines.append(f"- New path: `{row['new_tool_path']}`")
            lines.append(f"- Primary reasons: `{row['primary_failure_reasons']}`")
            if row.get("new_graph_evidence"):
                lines.append(f"- New graph evidence: `{row['new_graph_evidence']}`")
            lines.append(f"- Why baseline was right: {why_right}")
            lines.append(f"- Why new run failed: {why_wrong}")
            lines.append("- Baseline evidence chain:")
            for step in baseline.steps[:8]:
                lines.append(f"  - {_step_line(step)}")
            lines.append("- New evidence chain:")
            for step in new.steps[:10]:
                lines.append(f"  - {_step_line(step)}")
            lines.append("")

        if category == "weak_graph_hit":
            lines.append("Targeted improvements:")
            lines.append("")
            lines.append("- Add a graph-confidence gate: when top graph hit is fallback-only, zero-match, or misses the temporal anchor, demote graph evidence and force `clip_search_tool` or `frame_inspect_tool` before answering.")
            lines.append("- Pass the explicit `time_reference` into graph queries and ranking, then reject segment hits that are outside the target span for temporal questions.")
            lines.append("- For movie/news/live classification questions, enrich graph retrieval with caption keywords or scene-type cues instead of generic `person/crowd` relations.")
            lines.append("")
        elif category == "coarse_graph_replaced_fine_inspect":
            lines.append("Targeted improvements:")
            lines.append("")
            lines.append("- Add a question-type router: counting, color, appearance, and identity questions should require targeted `frame_inspect_tool` confirmation before `finish`.")
            lines.append("- Prefer `frame_graph_query_tool` over `segment_graph_query_tool` for fine-detail questions, or use segment graph only to localize and then immediately inspect exact frames.")
            lines.append("- Add a stop rule that blocks answers when the final evidence is still at segment summary level and no frame-level discriminator was observed.")
            lines.append("")
        else:
            lines.append("Targeted improvements:")
            lines.append("")
            lines.append("- Add answer-convergence checks: if the chain grows by 3+ LLM steps without stronger evidence, force an evidence recap and either inspect a final span or stop with the best-supported option.")
            lines.append("- Penalize tool loops that keep re-querying graph with paraphrases but do not improve temporal hit quality or match count.")
            lines.append("- Make `finish` require quoting the last decisive evidence source so later weak evidence cannot silently override an earlier stronger inspection result.")
            lines.append("")

    output_path.write_text("\n".join(lines), encoding="utf-8")
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description="Analyze correct->wrong regressions by failure mode.")
    parser.add_argument("--input-csv", required=True)
    parser.add_argument("--output-dir", required=True)
    args = parser.parse_args()

    input_csv = Path(args.input_csv).expanduser().resolve()
    output_dir = Path(args.output_dir).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    rows = _load_csv(input_csv)
    summary = _render_report(output_dir / "regression_3way_report.md", rows)
    _write_json(output_dir / "regression_3way_summary.json", summary)

    categorized: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        categorized[row["primary_failure_mode"]].append(row)

    for category, bucket in categorized.items():
        _write_csv(output_dir / f"regression_category_{category}.csv", bucket)

    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
